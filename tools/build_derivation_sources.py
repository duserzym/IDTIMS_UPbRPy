"""Refresh the website's source excerpts and immutable GitHub links."""
import ast
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
FILES = ['uncertainty.py', 'quality.py', 'utils.py', 'UPbR.py', 'UPb_grain.py', 'constants.py']


def main():
    revision = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip()
    entries = {}
    content = (ROOT / 'docs' / 'chapters.js').read_text()
    payload_text = content.split('const chapters = ', 1)[1].rstrip().removesuffix(';')
    chapters = json.loads(payload_text)
    wanted = {key for chapter in chapters for key in chapter['sources']}
    for filename in FILES:
        path = ROOT / 'src' / 'IDTIMS_UPbRPy' / filename
        source = path.read_text()
        lines = source.splitlines()
        relative = path.relative_to(ROOT).as_posix()
        def add(name, line, end):
            entries[filename + (':' + name if name else '')] = dict(
                file=relative, name=name, line=line,
                code='\n'.join(lines[line - 1:end]),
                url=f'https://github.com/duserzym/IDTIMS_UPbRPy/blob/{revision}/{relative}#L{line}')
        add('', 1, len(lines))
        tree = ast.parse(source)
        for node in tree.body:
            if isinstance(node, ast.FunctionDef):
                add(node.name, node.lineno, node.end_lineno)
            if isinstance(node, ast.ClassDef):
                for method in node.body:
                    if isinstance(method, ast.FunctionDef):
                        add(method.name, method.lineno, method.end_lineno)
    entries = {key: value for key, value in entries.items() if key in wanted}
    missing = wanted - entries.keys()
    if missing:
        raise ValueError(f'Missing source functions: {missing}')
    payload = dict(revision=revision, entries=entries)
    (ROOT / 'docs' / 'source-map.js').write_text(
        '// Generated by tools/build_derivation_sources.py; do not edit.\n'
        'const sourceMap = ' + json.dumps(payload, ensure_ascii=False, separators=(',', ':')) + ';\n')
    print(f'Captured {len(entries)} source connections at {revision[:10]}')


if __name__ == '__main__':
    main()
